# AI log: за допомогою ментора(AI) розібрався, як правильно формувати і повертати кортежі з генератора через yield,
# та закріпив розуміння різниці між об'єктом-генератором у пам'яті та його вичерпуванням через list().

def with_index(iterable, start=0):

    for it in iterable:

        yield (start, it)
        start += 1


# тут виводиться лише сам об'єкт класу генератор
print((with_index('abc', 1)))

# тут генератор спрацьовує і запаковуєтсья в лист
print(list(with_index('abc', 1)))
