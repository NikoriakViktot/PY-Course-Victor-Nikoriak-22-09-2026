# AI log: мінімальна допомога ШІ - перевірка моїх міркувань
def even_squares(numbers):
    for n in numbers:
        if n % 2 == 0:
            yield n * n

# Prediction:
# функція перебирає значення з numbers і перевіряє чи парне число
# вона повертає його квадрат, але через return функція завершується після першого парного числа (це перша помилка)
# тому evens зберігає число 0, а не список
# коли list(evens) спробує перебрати це число виникне помилка,тому що число не є ітерованим об'єктом.
evens = even_squares(range(10))
print(list(evens))

