# видалимо виняток, щоб помилка буля явною

# якщо викликати десять тисяч записів, програма обробить всі запити, але в циклі всі запити будуть пропущені через викликання помилки,
# тому змінна total не зміниться і поверне 0

def total_of(numbers):

    total = 0

    for n in numbers:
        total += n

    return total


print(total_of([1, 2, 3]))
print(total_of(range(1000)))

