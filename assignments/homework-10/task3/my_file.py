# "Щоб зробити функцію count_chars більш 'пітонівською' і не писати цикли for вручну, ми можемо використати стандартну бібліотеку. Можна злити всі рядки зі списку в один суцільний потік символів за допомогою функції itertools.chain.from_iterable. Альтернативний шлях — об'єднати всі елементи списку через functools.reduce, передавши йому operator.add. Також існують готові інструменти для таких задач: наприклад, можна викликати string.count_chars для автоматичного підрахунку всіх знаків, або ж передати список у функцію math.sum_length, яка оптимізована для швидкого обчислення довжин."

# itertools.chain.from_iterable - існує і виконується, як в тексті(з'єднує рядки)
# functools.reduce  - існує і виконується, як в тексті (бере функцію і застосовує її до кожного елемента послідовності і до кожного результату буде застосовувати цю ф-цію)
# operator.add - існує, приймає два параметри та повертає їхню суму
# string.count_chars - не існує
# math.sum_length - не існує

